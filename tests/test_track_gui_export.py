import os
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from tools.gui_common import REPOSITORY_ROOT
from tools.track_gui.design import CourseDesign, SectionSpec, skidpad_design
from tools.track_gui.export import (SaveRefused, check_model_id, check_title, describe_course,
                                    save_open_course)

TRACKS = REPOSITORY_ROOT / "models" / "tracks"


class ExportTests(unittest.TestCase):
    def setUp(self):
        self.course = skidpad_design(0.0).build()
        self._folder = tempfile.TemporaryDirectory()
        self.addCleanup(self._folder.cleanup)
        self.folder = Path(self._folder.name)

    def save(self, **keywords):
        arguments = dict(directory=self.folder, stem="t1", model_id="t1-id", title="T1")
        arguments.update(keywords)
        return save_open_course(self.course, **arguments)

    def test_saved_files_load_as_an_open_track(self):
        saved = self.save()
        self.assertFalse(saved.is_closed)
        self.assertAlmostEqual(saved.length, self.course.length, places=6)
        self.assertTrue(saved.xml.is_file() and saved.csv.is_file())
        self.assertEqual(sorted(p.name for p in self.folder.iterdir()), ["t1.csv", "t1.xml"])

    def test_awkward_text_is_written_as_valid_xml(self):
        saved = self.save(title="Tom & Jerry <1>", comments=["a note"])
        self.assertIn("Tom &amp; Jerry &lt;1&gt;", saved.xml.read_text())

    def test_bad_inputs_write_nothing(self):
        for key, value in (("stem", "bad name"), ("model_id", 'a"b'), ("title", ""),
                           ("title", "x\ny"), ("title", "x\x01y")):
            with self.subTest(key=key):
                with self.assertRaises(ValueError):
                    self.save(**{key: value})
        with self.assertRaisesRegex(ValueError, "comment"):
            self.save(comments=["bad -- comment"])
        self.assertEqual(list(self.folder.iterdir()), [])

    def test_existing_file_needs_overwrite(self):
        self.save()
        with self.assertRaisesRegex(SaveRefused, "already exists"):
            self.save()
        self.save(overwrite=True)

    def test_install_failure_cleans_new_csv(self):
        real_replace = os.replace
        calls = 0

        def fail_xml(source, target):
            nonlocal calls
            calls += 1
            if calls == 2:
                raise OSError("injected XML install failure")
            return real_replace(source, target)

        with mock.patch("tools.track_gui.export.os.replace", side_effect=fail_xml):
            with self.assertRaisesRegex(OSError, "injected"):
                self.save()
        self.assertEqual(list(self.folder.iterdir()), [])

    def test_install_failure_restores_existing_pair(self):
        self.save()
        before = {name: (self.folder / name).read_bytes() for name in ("t1.csv", "t1.xml")}
        real_replace = os.replace
        calls = 0

        def fail_xml(source, target):
            nonlocal calls
            calls += 1
            if calls == 4:
                raise OSError("injected XML install failure")
            return real_replace(source, target)

        with mock.patch("tools.track_gui.export.os.replace", side_effect=fail_xml):
            with self.assertRaisesRegex(OSError, "injected"):
                self.save(overwrite=True)
        self.assertEqual({name: (self.folder / name).read_bytes() for name in before}, before)

    def test_models_folder_needs_permission_and_nothing_is_written(self):
        before = sorted(p.name for p in TRACKS.iterdir())
        with self.assertRaisesRegex(SaveRefused, "models/"):
            self.save(directory=TRACKS, stem="zz_gui_probe")
        self.assertEqual(sorted(p.name for p in TRACKS.iterdir()), before)

    def test_generated_track_needs_its_own_confirmation(self):
        with tempfile.TemporaryDirectory() as folder:
            target = Path(folder)
            (target / "fsae_2026_skidpad.xml").write_text((TRACKS / "fsae_2026_skidpad.xml").read_text())
            with self.assertRaisesRegex(SaveRefused, "generated by tools/tracks/build_fsae_dynamic_tracks.py"):
                self.save(directory=target, stem="fsae_2026_skidpad", overwrite=True)
            self.save(directory=target, stem="fsae_2026_skidpad", overwrite=True, overwrite_generated=True)

    def test_committed_tracks_are_not_touched(self):
        digest = {p.name: p.read_bytes() for p in TRACKS.glob("fsae_2026_*")}
        self.save()
        self.assertEqual({p.name: p.read_bytes() for p in TRACKS.glob("fsae_2026_*")}, digest)

    def test_id_and_title_rules(self):
        self.assertEqual(check_model_id("a.b_c-1"), "a.b_c-1")
        for bad in ("", "-a", "a b", 'a"b', "x" * 81):
            with self.assertRaises(ValueError):
                check_model_id(bad)
        self.assertEqual(check_title("Hello"), "Hello")

    def test_describe_course(self):
        info = describe_course(CourseDesign((SectionSpec("arc-angle", radius=10.0, angle_deg=90.0),)).build())
        self.assertAlmostEqual(info["minimum_radius_m"], 10.0, places=3)
        self.assertAlmostEqual(info["heading_change_deg"], 90.0, places=3)
        straight = describe_course(CourseDesign((SectionSpec("straight", length=5.0),)).build())
        self.assertEqual(straight["minimum_radius_m"], float("inf"))


if __name__ == "__main__":
    unittest.main()
