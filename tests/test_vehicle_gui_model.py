import unittest

from tools.gui_common import REPOSITORY_ROOT
from tools.sim_gui.catalogue import candidates, read_entry, scan_catalogue
from tools.vehicle_gui.model import ASSEMBLY, VehicleEdit

MODELS = REPOSITORY_ROOT / "models"
FORMULATION = MODELS / "formulations" / "iem24_murphy_real_planar_7dof.xml"
CATALOGUE = scan_catalogue(MODELS)


def other_candidate(edit, key):
    current = edit.file(key)
    return next(c.path for c in candidates(read_entry(current), CATALOGUE) if c.path != current)


class ModelTests(unittest.TestCase):
    def setUp(self):
        self.edit = VehicleEdit.open(FORMULATION)

    def test_keys_start_with_the_assembly(self):
        self.assertEqual(self.edit.keys()[0], ASSEMBLY)
        self.assertIn("suspension/spring", self.edit.keys())

    def test_rows_carry_unit_and_text(self):
        row = next(r for r in self.edit.rows(ASSEMBLY) if r.name == "total_mass")
        self.assertEqual((row.original, row.unit, row.edited), ("287.0", "kg", None))

    def test_generated_slots_are_flagged_and_refuse_edits(self):
        self.assertTrue(self.edit.generator("suspension/spring"))
        self.assertIsNone(self.edit.generator(ASSEMBLY))
        name = self.edit.rows("suspension/spring")[0].name if self.edit.rows("suspension/spring") else None
        if name:
            with self.assertRaisesRegex(ValueError, "generated by"):
                self.edit.with_parameter("suspension/spring", name, 1.0)

    def test_edit_and_revert(self):
        edited = self.edit.with_parameter(ASSEMBLY, "total_mass", 300.0)
        self.assertTrue(edited.changed)
        self.assertEqual(next(r for r in edited.rows(ASSEMBLY) if r.name == "total_mass").edited, 300.0)
        self.assertFalse(edited.with_parameter(ASSEMBLY, "total_mass", 287.0).changed)
        self.assertFalse(edited.without_parameter(ASSEMBLY, "total_mass").changed)
        self.assertFalse(edited.reset().changed)
        self.assertFalse(self.edit.changed)

    def test_bad_edits_are_refused(self):
        for value in (float("nan"), float("inf")):
            with self.assertRaises(ValueError):
                self.edit.with_parameter(ASSEMBLY, "total_mass", value)
        with self.assertRaisesRegex(ValueError, "no parameter"):
            self.edit.with_parameter(ASSEMBLY, "nope", 1.0)
        with self.assertRaisesRegex(ValueError, "unknown slot"):
            self.edit.file("nope")

    def test_swapping_a_slot_drops_edits_below_it(self):
        edited = self.edit.with_parameter("powertrain/power-plant", self.edit.rows("powertrain/power-plant")[0].name,
                                          float(self.edit.rows("powertrain/power-plant")[0].original) * 1.1)
        swapped = edited.with_choice("powertrain", other_candidate(edited, "powertrain"))
        self.assertIn("powertrain", swapped.swapped())
        self.assertFalse(swapped.edited_keys())


if __name__ == "__main__":
    unittest.main()
