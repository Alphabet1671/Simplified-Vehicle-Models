import os
os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

import tempfile
import unittest
from pathlib import Path

try:
    from PyQt6.QtCore import Qt
    from PyQt6.QtWidgets import QApplication
except ImportError:
    QApplication = None

if QApplication is not None:
    from tools.gui_common import REPOSITORY_ROOT
    from tools.vehicle_gui.qt.main_window import MainWindow

FORMULATION = REPOSITORY_ROOT / "models" / "formulations" / "iem24_murphy_real_planar_7dof.xml"


def setUpModule():
    global app
    if QApplication is not None:
        app = QApplication.instance() or QApplication([])


def select(window, key):
    window.tree.setCurrentItem(window._items[key])


def set_value(window, name, text):
    for row in range(window.table.rowCount()):
        if window.table.index(row, 0).data() == name:
            return window.table.setData(window.table.index(row, 1), text)
    raise AssertionError(name)


@unittest.skipIf(QApplication is None, "PyQt6 is not installed")
class WindowTests(unittest.TestCase):
    def setUp(self):
        from PyQt6.QtWidgets import QMessageBox

        self.warnings = []
        self.infos = []
        original = (QMessageBox.question, QMessageBox.warning, QMessageBox.information)
        QMessageBox.question = staticmethod(lambda *a, **k: QMessageBox.StandardButton.Yes)
        QMessageBox.warning = staticmethod(lambda *a, **k: self.warnings.append(a[2]))
        QMessageBox.information = staticmethod(lambda *a, **k: self.infos.append(a[2]))
        self.addCleanup(
            lambda: (
                setattr(QMessageBox, "question", original[0]),
                setattr(QMessageBox, "warning", original[1]),
                setattr(QMessageBox, "information", original[2]),
            )
        )
        self.window = MainWindow()
        self.addCleanup(self.window.close)
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.window.folder.setText(str(Path(self._tmp.name) / "out"))
        self.assertTrue(self.window.open_path(FORMULATION))

    def test_open_shows_tree_table_and_a_green_verdict(self):
        self.assertTrue(self.window.tree.topLevelItem(0).childCount() > 3)
        self.assertGreater(self.window.table.rowCount(), 5)
        self.assertIn("compiles", self.window.verdict.text())
        self.assertIn("pitch_radius_of_gyration = 0.386 m", self.window.checks.toPlainText())

    def test_nothing_is_saved_without_a_change_prompt_on_close(self):
        self.assertFalse(self.window.edit.changed)

    def test_edit_marks_the_slot_and_saving_writes_copies(self):
        self.assertTrue(set_value(self.window, "cg_height", "0.315"))
        self.assertIn("edited", self.window.tree.topLevelItem(0).text(2))
        self.window.stem.setText("gui1")
        self.window.save_vehicle()
        self.assertTrue((Path(self._tmp.name) / "out" / "gui1__formulation.xml").is_file())

    def test_bad_text_is_refused_and_changes_nothing(self):
        messages = []
        self.window.table.refused.connect(messages.append)
        self.assertFalse(set_value(self.window, "cg_height", "abc"))
        self.assertFalse(set_value(self.window, "cg_height", "nan"))
        self.assertEqual(len(messages), 2)
        self.assertFalse(self.window.edit.changed)

    def test_value_the_compiler_rejects_turns_the_verdict_red(self):
        set_value(self.window, "total_mass", "-5")
        self.assertIn("does not compile", self.window.verdict.text())
        self.assertIn("total_mass must be positive", self.window.checks.toPlainText())
        set_value(self.window, "total_mass", "287")
        self.assertIn("compiles", self.window.verdict.text())

    def test_generated_slot_is_locked(self):
        select(self.window, "suspension/spring")
        self.assertIn("generated by tools/model_data/generate_suspension_lut.py", self.window.lock.text())
        index = self.window.table.index(0, 1)
        self.assertFalse(self.window.table.flags(index) & Qt.ItemFlag.ItemIsEditable)

    def test_swap_marks_the_slot_and_saves(self):
        select(self.window, "aero")
        self.assertGreater(self.window.swap.count(), 1)
        current = self.window.edit.file("aero")
        other = next(i for i in range(self.window.swap.count()) if self.window.swap.itemData(i) != current)
        self.window.swap.setCurrentIndex(other)
        self.window._swap()
        self.assertIn("swapped", self.window._items["aero"].text(2))
        self.window.stem.setText("gui2")
        self.window.save_vehicle()
        self.assertTrue((Path(self._tmp.name) / "out" / "gui2__vehicle.xml").is_file())

    def test_revert_slot(self):
        set_value(self.window, "cg_height", "0.315")
        self.window._revert_slot()
        self.assertFalse(self.window.edit.changed)

    def test_models_folder_is_refused_with_no_files_written(self):
        set_value(self.window, "cg_height", "0.315")
        self.window.folder.setText(str(REPOSITORY_ROOT / "models" / "vehicles"))
        self.window.stem.setText("zz_gui_probe")
        self.window.save_vehicle()
        self.assertTrue(self.warnings and "models/" in self.warnings[0])
        self.assertFalse(list((REPOSITORY_ROOT / "models" / "vehicles").glob("zz_gui_probe*")))

    def test_save_component_writes_a_new_component(self):
        select(self.window, "tire")
        self.window.stem.setText("my_tire")
        self.window.save_component(model_id="my-tire")
        self.assertTrue((Path(self._tmp.name) / "out" / "my_tire.xml").is_file())

    def test_geometry_is_restored_from_qsettings(self):
        from PyQt6.QtCore import QSettings
        from PyQt6.QtGui import QCloseEvent

        settings = QSettings("Simplified-Vehicle-Models", "vehicle-gui")
        settings.clear()
        self.window.resize(931, 617)
        event = QCloseEvent()
        self.window.closeEvent(event)
        self.assertTrue(event.isAccepted())
        restored = MainWindow()
        self.addCleanup(restored.close)
        self.assertEqual(restored.size().height(), self.window.size().height())
        self.assertGreater(restored.size().width(), 0)

    def test_close_rejects_unsaved_changes_when_question_says_no(self):
        from PyQt6.QtGui import QCloseEvent
        from PyQt6.QtWidgets import QMessageBox

        set_value(self.window, "cg_height", "0.315")
        original = QMessageBox.question
        QMessageBox.question = staticmethod(lambda *a, **k: QMessageBox.StandardButton.No)
        try:
            event = QCloseEvent()
            self.window.closeEvent(event)
            self.assertFalse(event.isAccepted())
        finally:
            QMessageBox.question = original

    def test_app_main_quits_after_the_hook(self):
        from tools.vehicle_gui import app as app_module

        os.environ["VEHICLE_GUI_QUIT_AFTER_MS"] = "50"
        self.addCleanup(os.environ.pop, "VEHICLE_GUI_QUIT_AFTER_MS", None)
        self.assertEqual(app_module.main([str(FORMULATION)]), 0)


if __name__ == "__main__":
    unittest.main()
