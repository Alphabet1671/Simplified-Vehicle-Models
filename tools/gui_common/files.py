"""Safe file writing and the checks the three GUIs share."""
from __future__ import annotations

import json
import os
import re
from pathlib import Path
from typing import Any

from tools.gui_common import REPOSITORY_ROOT

#: The name rule of ``tools/model_data/generate_component_sweep.py``.
NAME_PATTERN = re.compile(r"[A-Za-z0-9_-]{1,40}")

_GENERATED = re.compile(r"<!--(?:(?!-->).)*?Generated by\s+(tools/[\w./-]+)", re.S)


def check_name(value: str, what: str = "name") -> str:
    """Return ``value`` when it is 1 to 40 letters, digits, ``_`` or ``-``."""
    if not NAME_PATTERN.fullmatch(value or ""):
        raise ValueError(f"{what} must be 1 to 40 characters of letters, digits, _ or -: {value!r}")
    return value


def atomic_write_text(path: Path, text: str) -> None:
    """Write ``text`` to ``path`` through a temporary file in the same folder."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    with open(temporary, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(text)
    os.replace(temporary, path)


def atomic_write_json(path: Path, payload: Any) -> None:
    """Write JSON with the repository settings: sorted keys, no NaN."""
    atomic_write_text(path, json.dumps(payload, indent=2, sort_keys=True, allow_nan=False) + "\n")


def is_inside(path: Path, root: Path) -> bool:
    """Return True when ``path`` is ``root`` or lies below it (links resolved)."""
    try:
        Path(path).resolve().relative_to(Path(root).resolve())
    except ValueError:
        return False
    return True


def generated_by(path: Path) -> str | None:
    """Return the generator named in a ``Generated by tools/...`` XML comment, or None."""
    try:
        text = Path(path).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None
    match = _GENERATED.search(text)
    return match.group(1).rstrip(".") if match else None


def protected_directory_problem(directory: Path, *, allow_models: bool) -> str | None:
    """Return a message when ``directory`` is inside ``models/`` without permission.

    ``models/sweeps/`` is exempt: it is git-ignored and the catalogue skips it.
    """
    models = REPOSITORY_ROOT / "models"
    if is_inside(directory, models / "sweeps"):
        return None
    if is_inside(directory, models) and not allow_models:
        return (f"{directory} is inside models/. Many tests pin the hashes of the files "
                f"there, so writing needs an explicit confirmation")
    return None
