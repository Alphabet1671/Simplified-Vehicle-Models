"""Deterministically generate a hydraulic circuit NPZ and its component XML.

The example is a per-axle roll-decoupled circuit: each wheel has one cylinder into
its own gas accumulator node, and an orifice line joins the left and right nodes
of each axle. In the stiff-line limit the two nodes of an axle share one pressure,
so the circuit adds heave stiffness and no roll stiffness; with closed lines every
wheel has its own gas spring.

Every value is PROPOSED. There is no measured hydraulic data for this car. The
defaults are sized so the closed circuit fits the +-31.8 mm jounce travel plus the
10 mm trial margin with the gas between its stops.

The NPZ is byte-reproducible: the zip entries carry a fixed timestamp and are
stored uncompressed, and no path or time enters the bytes.

    python3 tools/model_data/generate_hydraulic_circuit.py \\
        --output-npz models/data/iem24_roll_decoupled_circuit.npz \\
        --output-xml models/hydraulics/iem24_roll_decoupled_circuit.xml
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
import shlex
import sys
import zipfile
from pathlib import Path

import numpy as np

GENERATOR_VERSION = "hydraulic-circuit-v1"
SCHEMA = "hydraulic-circuit-v1"
_ZIP_TIME = (1980, 1, 1, 0, 0, 0)
ATMOSPHERE = 101325.0

NODE_NAMES = ("fl", "fr", "rl", "rr")
DEFAULTS = {
    "area": 1.5e-3,                   # m^2 wheel-referred cylinder area
    "precharge_pressure": 5.0e5,      # Pa gauge
    "design_pressure": 1.2e6,         # Pa gauge
    "precharge_volume": 2.5e-4,       # m^3
    "minimum_volume": 4.0e-5,         # m^3
    "exponent": 1.4,
    "line_linear": 3.0e8,             # Pa s/m^3
    "line_quadratic": 5.0e11,         # Pa s^2/m^6
}


class CircuitError(ValueError):
    """Report an invalid generator input."""


def circuit_arrays(**overrides) -> dict:
    """Return the arrays of the roll-decoupled example circuit."""

    unknown = sorted(set(overrides) - set(DEFAULTS))
    if unknown:
        raise CircuitError(f"unknown circuit parameters {unknown}")
    p = {**DEFAULTS, **overrides}
    if not (p["design_pressure"] > p["precharge_pressure"] > -ATMOSPHERE):
        raise CircuitError("the design pressure must exceed the precharge pressure")
    if not 0.0 < p["minimum_volume"] < p["precharge_volume"]:
        raise CircuitError("minimum_volume must lie in (0, precharge_volume)")
    count = len(NODE_NAMES)
    metadata = {"parameters": p, "status": "PROPOSED",
                "layout": "per-axle roll-decoupled; lines fl-fr and rl-rr"}
    return {
        "schema": np.asarray(SCHEMA),
        "generator_version": np.asarray(GENERATOR_VERSION),
        "metadata": np.asarray(json.dumps(metadata, sort_keys=True, separators=(",", ":"))),
        "node_names": np.asarray(NODE_NAMES),
        "areas": p["area"] * np.eye(count),
        "precharge_pressure": np.full(count, p["precharge_pressure"]),
        "precharge_volume": np.full(count, p["precharge_volume"]),
        "exponent": np.full(count, p["exponent"]),
        "minimum_volume": np.full(count, p["minimum_volume"]),
        "design_pressure": np.full(count, p["design_pressure"]),
        "line_from": np.asarray([0, 2], dtype=np.int64),
        "line_to": np.asarray([1, 3], dtype=np.int64),
        "line_linear": np.full(2, p["line_linear"]),
        "line_quadratic": np.full(2, p["line_quadratic"]),
    }


def npz_bytes(arrays) -> bytes:
    """Serialize arrays to deterministic NPZ bytes (stored, fixed timestamps)."""

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_STORED) as archive:
        for name, array in arrays.items():
            payload = io.BytesIO()
            np.lib.format.write_array(payload, np.asanyarray(array), allow_pickle=False)
            info = zipfile.ZipInfo(f"{name}.npy", date_time=_ZIP_TIME)
            info.compress_type = zipfile.ZIP_STORED
            info.create_system = 3
            info.external_attr = 0o600 << 16
            archive.writestr(info, payload.getvalue())
    return buffer.getvalue()


def atomic_write_bytes(path, data: bytes) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    try:
        with temporary.open("wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def circuit_xml(model_id: str, npz_relative: str, digest: str, line_scale: float = 1.0) -> str:
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f"<!-- Generated by tools/model_data/generate_hydraulic_circuit.py ({GENERATOR_VERSION}). Do not edit.\n"
        "     PROPOSED: a per-axle roll-decoupled hydraulic circuit, four cylinder/accumulator nodes\n"
        "     and a left-right orifice line on each axle. There is no measured hydraulic data;\n"
        "     every cylinder area, precharge, volume and orifice value is a sizing choice.\n"
        "     line_scale multiplies every orifice resistance. The NPZ sha256 pins the circuit. -->\n"
        f'<model schema-version="1.0" id="{model_id}" type="hydraulic-circuit" subtype="npz">\n'
        "  <parameters>\n"
        f'    <parameter name="line_scale" value="{line_scale}" unit="1"/>\n'
        "  </parameters>\n"
        f'  <data role="circuit-table" path="{npz_relative}" format="npz" sha256="{digest}"/>\n'
        "</model>\n"
    )


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--output-npz", required=True)
    parser.add_argument("--output-xml")
    for name, value in DEFAULTS.items():
        parser.add_argument(f"--{name.replace('_', '-')}", type=float, default=value)
    return parser


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    args = build_parser().parse_args(argv)
    try:
        arrays = circuit_arrays(**{name: getattr(args, name) for name in DEFAULTS})
    except CircuitError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    data = npz_bytes(arrays)
    digest = hashlib.sha256(data).hexdigest()
    npz_path = Path(args.output_npz)
    atomic_write_bytes(npz_path, data)
    if args.output_xml:
        target = Path(args.output_xml)
        relative = Path(os.path.relpath(npz_path.resolve(), target.resolve().parent)).as_posix()
        atomic_write_bytes(
            target, circuit_xml(target.stem.replace("_", "-"), relative, digest).encode("utf-8"))
    print(f"SHA-256: {digest}")
    print("command: python3 tools/model_data/generate_hydraulic_circuit.py " + shlex.join(argv))
    return 0


if __name__ == "__main__":
    sys.exit(main())
