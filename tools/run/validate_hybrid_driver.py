def time_weighted_deceleration(time_s,speed_mps,*,start_s,end_s):
    """Mean forward-difference deceleration with actual-time weighting."""
    t=np.asarray(time_s,dtype=float);v=np.asarray(speed_mps,dtype=float)
    if t.ndim!=1 or v.shape!=t.shape or len(t)<2 or not np.all(np.isfinite(t)) or not np.all(np.isfinite(v)):
        raise ValueError('finite matching one-dimensional time/speed arrays required')
    if np.any(np.diff(t)<=0) or not np.isfinite(start_s+end_s) or end_s<=start_s:
        raise ValueError('strict time grid and positive measurement interval required')
    if start_s<t[0] or end_s>t[-1]: raise ValueError('empty measurement interval is not fully covered by trace')
    interior=(t>start_s)&(t<end_s);tt=np.r_[start_s,t[interior],end_s]
    vv=np.interp(tt,t,v);dt=np.diff(tt)
    if len(dt)==0 or np.any(dt<=0): raise ValueError('empty measurement interval')
    decel=-np.diff(vv)/dt
    return {'duration_s':float(end_s-start_s),'mean_deceleration_mps2':float(np.sum(decel*dt)/(end_s-start_s)),
            'maximum_absolute_deceleration_error_mps2':None,'samples':int(len(tt))}


def hold_gate_metrics(time_s,speed_mps,target_mps2,*,start_s,end_s,eligible=None):
    """Metric gate; eligibility must be a contiguous Boolean time interval."""
    target=float(target_mps2)
    if not np.isfinite(target) or target<=0: raise ValueError('target must be positive finite')
    t=np.asarray(time_s,dtype=float);v=np.asarray(speed_mps,dtype=float)
    if eligible is not None:
        e=np.asarray(eligible,dtype=bool)
        if e.shape!=t.shape: raise ValueError('eligibility shape mismatch')
        ix=np.flatnonzero((t>=start_s)&(t<=end_s)&e)
        if len(ix)<2 or np.any(np.diff(ix)!=1): raise ValueError('eligible window is empty or non-contiguous')
        start_s=float(t[ix[0]]);end_s=float(t[ix[-1]])
    base=time_weighted_deceleration(t,v,start_s=start_s,end_s=end_s)
    tt=np.r_[start_s,t[(t>start_s)&(t<end_s)],end_s];vv=np.interp(tt,t,v);dt=np.diff(tt);decel=-np.diff(vv)/dt
    limit=max(.25,.05*target)
    base.update({'target_mps2':target,'maximum_absolute_deceleration_error_mps2':float(np.max(np.abs(decel-target))),
                 'threshold_mps2':limit,'pass':bool(abs(base['mean_deceleration_mps2']-target)<=limit and np.max(np.abs(decel-target))<=limit),
                 'start_s':float(start_s),'end_s':float(end_s)})
    return base


def _pedal_rate(p,command,pc):
    delta=command-p
    if p>0.: limit=pc.throttle_release_rate if delta<0. else (pc.throttle_apply_rate or pc.throttle_release_rate)
    elif p<0.: limit=(pc.brake_release_rate or pc.brake_apply_rate) if delta>0. else pc.brake_apply_rate
    else: limit=(pc.throttle_apply_rate or pc.throttle_release_rate) if delta>=0. else pc.brake_apply_rate
    return float(np.clip(delta/pc.pedal_time_constant,-limit,limit))


def _generator_pedal_command(raw_acceleration,context,predictor,maximum_pedal_force_n):
    """Map signed reference acceleration into signed normalized pedal."""
    raw=float(raw_acceleration);force_max=float(maximum_pedal_force_n)
    if raw>0.: return min(1.,raw/2.5)
    if raw<0.: return -float(predictor.request_current(context,-raw).pedal_force_n)/force_max
    return 0.


def _physical_pedal_acceleration(model,predictor,context,speed,pedal,soc):
    """Shared reduced-generator/replay forward oracle in the frozen context."""
    force_max=float(model.planar.maximum_pedal_force)
    if pedal < 0.:
        return -float(predictor.predict(context,float(-pedal)*force_max).deceleration_mps2)
    driven,gearing,efficiency=_drivetrain_context(model.planar)
    radii=np.asarray(context.wheel_radii_m,dtype=float)
    v=max(float(speed),.01)
    pt=evaluate_forward_powertrain(model.planar,driven,gearing,efficiency,np.full(4,v)/radii,soc,DriverCommand(float(pedal),0.,0.))
    motor_force=float(np.sum(np.asarray(pt.motor_wheel_torques)/radii))
    coast=-float(predictor.predict(context,0.).deceleration_mps2)
    effective_mass=float(model.planar.total_mass+model.planar.wheel_inertia*np.sum(1./radii**2))
    return motor_force/effective_mass+coast


def prospective_hold_fixed_point(model,target,initial_pedal,provider,predictor,pc,*,maximum_iterations=MAX_HOLD_ITERATIONS,evidence_prefix=None,source_hashes_before=None):
    """Build one prospective coupled reference, then independently replay it.

    The offline generator and reduced replay share the same current-context
    forward pedal oracle; the replay still obtains commands from the real
    HybridLongitudinalPolicy. The declared hold transition is at 0.60 s, while
    the separate measurement window begins at 0.95 s.
    """
    if maximum_iterations>MAX_HOLD_ITERATIONS: raise ValueError('at most eight prospective reduced replays are permitted')
    old=SpeedPlan(np.array([0.,100.]),np.array([40.,40.]),np.zeros(2),False)
    plant=VerticalForwardPlant(model,old);initial=plant.initial_state(20.);soc=float(initial[SOC_INDEX])
    c0=plant.brake_authority_context(initial,predictor=predictor)
    force_max=float(model.planar.maximum_pedal_force)
    def current_context(speed):
        # Frozen initial loads/radii/SOC are the fixture's immutable actuator context.
        return BrakeAuthorityContext(max(float(speed),.01),0.,c0.wheel_radii_m,c0.normal_loads_n,soc=soc)
    def physical_acceleration(speed,pedal):
        """Signed forward oracle used by both generator and replay."""
        return _physical_pedal_acceleration(model,predictor,current_context(speed),speed,pedal,soc)
    def ode_rhs(t,y):
        s,v,p,r=map(float,y);v=max(v,.01);r=max(r,.01)
        # Predeclared transition is at .60 s; .95 s is only the measurement
        # window start after the .35 s settling allowance.
        raw=0. if t<HOLD_TIME_S else -float(target)
        p_cmd=_generator_pedal_command(raw,current_context(v),predictor,force_max)
        pdot=_pedal_rate(p,p_cmd,pc)
        vdot=physical_acceleration(v,p)
        # Correct station/time conversion: a_ref=r*dr/ds and ds/dt=v.
        # Thus dr/dt=(v/r)*a_ref; omitting v/r is wrong unless v==r.
        # The reduced reference is dynamically coupled to its forecast model;
        # no actual-policy or realized vehicle trace enters its construction.
        aref=raw-2.0*(r-v)
        rdot=(v/r)*aref
        return [v,vdot,pdot,rdot]
    # Forecast beyond the actual 2 s run so no reference-horizon edge lands
    # inside the measurement window; this horizon is predeclared, not data-fit.
    forecast_end_s=3.0
    sol=solve_ivp(ode_rhs,(0.,forecast_end_s),[0.,20.,float(initial_pedal),20.],method='RK45',rtol=1e-8,atol=1e-10,max_step=.002,dense_output=True)
    if not sol.success: raise RuntimeError('prospective coupled ODE failed: '+sol.message)
    # Sample at fixed station increment; keep dense prospective lead+hold
    # reference, then analytic continuation with the actual prospective slope.
    stations=np.arange(0.,100.001,.10)
    # Invert the complete monotone prospective station history; clamp only
    # beyond its true 2 s endpoint. This is a single fixed-grid resampling.
    times=np.interp(stations,sol.y[0],sol.t,left=0.,right=float(sol.t[-1]))
    ref=np.asarray(sol.sol(np.minimum(times,float(sol.t[-1])))[3],dtype=float)
    s_end=float(sol.y[0,-1]);r_end=float(sol.y[3,-1])
    aft=stations>s_end
    ref[aft]=r_end
    ref=np.maximum(ref,.02)
    plan=build_hybrid_speed_plan(stations,np.zeros_like(stations),ref,provider,initial_speed_mps=20.,storage_soc=soc,is_closed=False)
    # Independent final-plan reduced replay through REAL policy, within declared
    # forecast-to-plan residual limits; one replay, no actual truth feedback.
    policy=HybridLongitudinalPolicy(plan,provider,predictor,HybridPolicyConfig(maximum_brake_force_n=force_max,pedal_context=pc))
    replay_trace=[]
    def replay_rhs(t,y):
        s,v,p=map(float,y);v=max(v,.01)
        obs=__import__('simplified_vehicle_models.solvers.forward_driver',fromlist=['DriverObservation']).DriverObservation(s,0.,0.,v,0.,0.,wheel_speed_margin=1.)
        kin=__import__('simplified_vehicle_models.solvers.longitudinal_capability',fromlist=['PathKinematicContext']).PathKinematicContext(v,0.,0.,0.,0.,0.,0.,0.,True)
        ctx=current_context(v)
        dec=policy.decide(observation=obs,pedal_position=p,kinematics=kin,soc=soc,brake_context=ctx)
        sample=plan.sample(s)
        command=dec.throttle-dec.brake_force_n/force_max
        pdot=_pedal_rate(p,command,pc)
        acceleration=physical_acceleration(v,p)
        replay_trace.append((t,s,v,p,sample.speed_mps,sample.acceleration_mps2,sample.braking_region,sample.distance_to_binding_event_m,sample.distance_to_braking_onset_m,dec.decision.raw_acceleration_request_mps2,dec.decision.target_progress_acceleration_mps2,dec.decision.phase,dec.decision.status,command,acceleration,dec.first_pedal_target,dec.predicted_pedal_after_first_slab))
        return [v,acceleration,pdot]
    replay=solve_ivp(replay_rhs,(0.,3.),[0.,20.,float(initial_pedal)],method='RK45',rtol=1e-8,atol=1e-10,max_step=.002,dense_output=True)
    if not replay.success: raise RuntimeError('frozen plan production-policy preflight replay failed')
    forecast_s=float(sol.y[0,-1]);forecast_v=float(sol.y[1,-1]);forecast_r=float(sol.y[3,-1]);replay_s=float(replay.y[0,-1]);replay_v=float(replay.y[1,-1])
    residual_v=replay_v-forecast_v;residual_s=replay_s-forecast_s
    replay_anchor=np.asarray(replay.sol(HOLD_TIME_S));forecast_anchor=np.asarray(sol.sol(HOLD_TIME_S))
    anchor_residual_v=float(replay_anchor[1]-forecast_anchor[1]);anchor_residual_s=float(replay_anchor[0]-forecast_anchor[0])
    replay_end2=np.asarray(replay.sol(2.));forecast_end2=np.asarray(sol.sol(2.))
    end2_residual_v=float(replay_end2[1]-forecast_end2[1]);end2_residual_s=float(replay_end2[0]-forecast_end2[0])
    if abs(anchor_residual_v)>HOLD_SPEED_TOLERANCE_MPS or abs(anchor_residual_s)>HOLD_STATION_TOLERANCE_M or abs(end2_residual_v)>HOLD_SPEED_TOLERANCE_MPS or abs(end2_residual_s)>HOLD_STATION_TOLERANCE_M:
        divergence=next((row for row in replay_trace if row[0]>=HOLD_TIME_S and (str(row[11]) not in ('coast','brake','drive') or abs(row[10]+target)>.05)),None)
        divergence_detail=None
        if divergence is not None:
            td,sd,vd,pd,qv,qa,region,binding,onset,raw_request,policy_target,phase,status,actual_command,actual_accel,*_=divergence
            gen_raw=0. if td<HOLD_TIME_S else -float(target)
            gen_command=_generator_pedal_command(gen_raw,current_context(vd),predictor,force_max)
            divergence_detail={'time_s':float(td),'station_m':float(sd),'speed_mps':float(vd),'reference_speed_mps':float(qv),'sampled_plan_acceleration_mps2':float(qa),'policy_raw_request_mps2':float(raw_request),'policy_target_mps2':float(policy_target),'policy_phase':str(phase),'replay_pedal':float(pd),'replay_command':float(actual_command),'replay_forward_acceleration_mps2':float(actual_accel),'generator_raw_request_mps2':float(gen_raw),'generator_command':float(gen_command),'generator_forward_acceleration_at_same_state_mps2':float(physical_acceleration(vd,gen_command)),'shared_forward_acceleration_at_replay_pedal_mps2':float(physical_acceleration(vd,pd))}
        failure={'reason':'frozen prospective plan replay mismatch at declared hold handoff','target_mps2':float(target),'initial_pedal':float(initial_pedal),'hold_time_s':HOLD_TIME_S,'settle_after_hold_s':SETTLE_AFTER_HOLD_S,'measurement_window_s':[HOLD_TIME_S+SETTLE_AFTER_HOLD_S,2.0],'anchor_speed_residual_mps':anchor_residual_v,'anchor_station_residual_m':anchor_residual_s,'forecast_endpoint_speed_residual_mps':residual_v,'forecast_endpoint_station_residual_m':residual_s,'run_end2_speed_residual_mps':end2_residual_v,'run_end2_station_residual_m':end2_residual_s,'forecast_reference_endpoint_mps':forecast_r,'first_postlead_policy_divergence':divergence_detail,'trace_rows':len(replay_trace),'plan_identity':plan.identity,'provider_identity':provider.identity,'model_hash':provider.model_hash,'source_closure_hash':provider.source_closure_hash}
        if evidence_prefix is not None:
            prefix=Path(evidence_prefix);prefix.parent.mkdir(parents=True,exist_ok=True)
            numeric=np.asarray([[float(x) if x is not None else float('nan') for x in row[:11]]+[float(row[13]),float(row[14]),float(row[15]) if row[15] is not None else float('nan'),float(row[16]) if row[16] is not None else float('nan')] for row in replay_trace])
            np.savez_compressed(str(prefix)+'.npz',forecast_time=sol.t,forecast_s=sol.y[0],forecast_v=sol.y[1],forecast_p=sol.y[2],forecast_r=sol.y[3],replay_time=replay.t,replay_s=replay.y[0],replay_v=replay.y[1],replay_p=replay.y[2],replay_numeric=numeric,replay_phase=np.asarray([str(row[11]) for row in replay_trace],dtype='U32'),replay_status=np.asarray([str(row[12]) for row in replay_trace],dtype='U64'),plan_station=plan.distance_m,plan_speed=plan.speed_mps,plan_acceleration=plan.acceleration_mps2,plan_braking_bound=plan.braking_speed_bound_mps,plan_binding_index=plan.binding_index)
            source_hashes={name:hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in CORE_SOURCE_NAMES}
            config={'hold_time_s':HOLD_TIME_S,'settle_after_hold_s':SETTLE_AFTER_HOLD_S,'measurement_window_s':[HOLD_TIME_S+SETTLE_AFTER_HOLD_S,2.0],'target_mps2':float(target),'initial_pedal':float(initial_pedal),'station_grid_m':.10,'forecast_horizon_s':forecast_end_s,'oracle':'signed normalized pedal; negative acceleration inverse explicitly returns negative brake pedal; shared BrakeAuthorityPredictor current-context forward for brake, compiled powertrain + predictor coast and effective mass for drive','source_sha256':source_hashes,'provider_identity':provider.identity,'model_hash':provider.model_hash,'source_closure_hash':provider.source_closure_hash}
            failure['config']=config
            Path(str(prefix)+'.json').write_text(json.dumps(failure,indent=2,sort_keys=True)+'\n')
        raise RuntimeError(json.dumps(failure,sort_keys=True))
    source_hashes_after={name:hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in CORE_SOURCE_NAMES}
    if source_hashes_before is not None and source_hashes_after!=source_hashes_before:
        raise RuntimeError('production source changed during prospective fixture run; evidence identity invalidated')
    if evidence_prefix is not None:
        prefix=Path(evidence_prefix);prefix.parent.mkdir(parents=True,exist_ok=True)
        numeric=np.asarray([[float(x) if x is not None else float('nan') for x in row[:11]]+[float(row[13]),float(row[14]),float(row[15]) if row[15] is not None else float('nan'),float(row[16]) if row[16] is not None else float('nan')] for row in replay_trace])
        np.savez_compressed(str(prefix)+'.npz',forecast_time=sol.t,forecast_s=sol.y[0],forecast_v=sol.y[1],forecast_p=sol.y[2],forecast_r=sol.y[3],replay_time=replay.t,replay_s=replay.y[0],replay_v=replay.y[1],replay_p=replay.y[2],replay_numeric=numeric,replay_phase=np.asarray([str(row[11]) for row in replay_trace],dtype='U32'),replay_status=np.asarray([str(row[12]) for row in replay_trace],dtype='U64'),plan_station=plan.distance_m,plan_speed=plan.speed_mps,plan_acceleration=plan.acceleration_mps2,plan_braking_bound=plan.braking_speed_bound_mps,plan_binding_index=plan.binding_index)
    return {'plan':plan,'initial_state':initial,'soc':soc,'hold_time_s':HOLD_TIME_S,
            'iterations':[{'iteration':1,'hold_handoff_speed_residual_mps':anchor_residual_v,'hold_handoff_station_residual_m':anchor_residual_s,'forecast_endpoint_speed_residual_mps':residual_v,'forecast_endpoint_station_residual_m':residual_s,'run_end2_speed_residual_mps':end2_residual_v,'run_end2_station_residual_m':end2_residual_s}],
            'plan_anchor_speed_mps':float(np.interp(HOLD_TIME_S,sol.t,sol.y[1])),'plan_anchor_station_m':float(np.interp(HOLD_TIME_S,sol.t,sol.y[0])),
            'replayed_anchor_speed_mps':float(replay_anchor[1]),'replayed_anchor_station_m':float(replay_anchor[0]),'converged':True,'prospective_only':True,
            'reference_time_s':sol.t,'reference_state':sol.y,'reference_equation':'coupled prospective model; raw lead/hold uses mapped pedal forecast acceleration compensation; 3s forecast, 2s actual run',
        'reduced_generator_role':'fixture-only inverse forecast; actual execution uses REAL policy and plant',
        'reference_node_source':'single coupled ODE dense-output station inversion at 0.10 m; frozen once through normal builder'}


def run_hold_case(model,target,initial_pedal,*,trace_path=None,evidence_prefix=None,source_hashes_before=None):
    """Run one actual 38-state production-path hold after prospective preflight."""
    from simplified_vehicle_models.solvers.forward_driver import DriverObservation, StepSample
    vehicle=model.planar;pc=PedalPolicyContext(1/.175,1/.175,.02,vehicle.maximum_pedal_force,.85,1/.175,1/.175)
    provider=CurrentVehicleCapability(vehicle,wheel_radii_m=(.29,)*4,speed_grid_mps=(.01,10.,20.,40.),curvature_grid_inv_m=(-.001,.001),soc_grid=(.8,.9),source_label='task5-actual-38state',calibration_label='compiled-IEM-current')
    predictor=BrakeAuthorityPredictor(vehicle,maximum_abs_curvature_inv_m=.001,minimum_speed_mps=.01,maximum_speed_mps=40.)
    prospective=prospective_hold_fixed_point(model,target,initial_pedal,provider,predictor,pc,evidence_prefix=evidence_prefix,source_hashes_before=source_hashes_before)
    old=SpeedPlan(np.array([0.,100.]),np.array([40.,40.]),np.zeros(2),False)
    plant=VerticalForwardPlant(model,old);rows=[]
    driver=PreviewDriver(old,vehicle.wheelbase,vehicle.steering_maximum_angle,vehicle.steering_maximum_rate,vehicle.maximum_pedal_force,pedal_travel_time=.175,hybrid_policy=HybridLongitudinalPolicy(prospective['plan'],provider,predictor,HybridPolicyConfig(maximum_brake_force_n=vehicle.maximum_pedal_force,pedal_context=pc)))
    driver=replace(driver,throttle_apply_rate=1/.175,throttle_release_rate=1/.175,brake_apply_rate=1/.175,brake_release_rate=1/.175)
    start=time.perf_counter();result=solve_forward(plant,driver,prospective['initial_state'],duration=2.,wall_seconds=90.,maximum_wall_seconds=90.,maximum_step=.01,rtol=2e-5,atol=1e-7,method='BDF',initial_pedal=initial_pedal,step_sink=rows.append)
    hashes_after={name:hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in CORE_SOURCE_NAMES}
    if source_hashes_before is not None and hashes_after!=source_hashes_before: raise RuntimeError('production source changed during actual hold; evidence identity invalidated')
    wall=time.perf_counter()-start
    times=np.array([r.time for r in rows]);speeds=np.array([plant.observe(r.state).speed for r in rows])
    start_s=prospective['hold_time_s']+SETTLE_AFTER_HOLD_S;metrics=hold_gate_metrics(times,speeds,target,start_s=start_s,end_s=2.)
    eligible=[]
    for r in rows:
        # Request/applied parity is expressed in the production driver's
        # normalized pedal coordinate, not Newtons divided by Fmax.
        req=r.requested_command.throttle-r.requested_command.brake_force/driver.maximum_brake_force
        app=r.pedal if r.pedal is not None else (r.command.throttle-r.command.brake_force/driver.maximum_brake_force)
        eligible.append(abs(req-app)<=.01)
    ix=np.flatnonzero((times>=metrics['start_s'])&(times<=metrics['end_s']))
    metrics['request_applied_within_1pct']=bool(len(ix)>=2 and np.all(np.asarray(eligible)[ix]))
    metrics['solver_reached_end']=bool(rows[-1].time>=2.-1e-9);metrics['finite_actual_state']=bool(np.all(np.isfinite(result.state)))
    metrics['nonnegative_contact']=bool(plant.minimum_contact_load>=0.)
    metrics['pass']=bool(metrics['pass'] and metrics['request_applied_within_1pct'] and metrics['solver_reached_end'] and metrics['finite_actual_state'] and metrics['nonnegative_contact'])
    metrics['wall_seconds']=wall;metrics['accepted_steps']=len(rows);metrics['solver_evaluations']=result.evaluations
    metrics['raw_target_pedal_metrics']={'max_requested_signed_pedal':float(max(abs(r.requested_command.throttle-r.requested_command.brake_force/driver.maximum_brake_force) for r in rows)),'max_applied_signed_pedal':float(max(abs(r.pedal) for r in rows)),'max_raw_request_mps2':float(max(abs(r.policy_diagnostics.raw_acceleration_request_mps2) for r in rows)),'max_target_progress_acceleration_mps2':float(max(abs(r.policy_diagnostics.target_progress_acceleration_mps2) for r in rows))}
    metrics['source_hashes_before_after_stable']=source_hashes_before
    metrics['prospective_anchor']={k:v for k,v in prospective.items() if k not in ('plan','initial_state','reference_time_s','reference_state')}
    metrics['plan_identity']=prospective['plan'].identity;metrics['provider_identity']=provider.identity
