"""Write isolated XML model variants for simulation cases."""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from xml.etree import ElementTree

from tools.model_data.xml_references import relative_reference, rewrite_references


@dataclass(frozen=True, slots=True)
class VariantFiles:
    formulation: Path
    vehicle: Path


def _case_suffix(case_id: str) -> str:
    return case_id.replace("_", "-")


def _output_name(key: str) -> str:
    return key.replace("/", "__") + ".xml"


def _components(path: Path):
    return ElementTree.parse(path).getroot().findall("./components/component")


def _write_tree(tree, destination: Path, case_id: str, source: Path) -> None:
    """Serialize an ElementTree and put the provenance comment before its root."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    import io
    stream = io.BytesIO()
    tree.write(stream, encoding="UTF-8", xml_declaration=True)
    payload = stream.getvalue()
    marker = b"?>"
    index = payload.find(marker)
    declaration = payload[: index + len(marker)] if index >= 0 else b'<?xml version="1.0" encoding="UTF-8"?>'
    body = payload[index + len(marker):] if index >= 0 else payload
    comment = f"\n<!-- Generated by tools/sim_gui for {case_id} from {source}. Do not edit. -->\n".encode()
    destination.write_bytes(declaration + comment + body.lstrip())


def _variant_tree(source: Path, directory: Path, case_id: str,
                  replace: dict[str, Path]):
    tree = ElementTree.parse(source)
    root = tree.getroot()
    root.set("id", f"{root.get('id', '')}.{_case_suffix(case_id)}")
    rewrite_references(tree, source.parent, directory, replace)
    return tree


def write_variant(configuration, directory: Path, case_id: str) -> VariantFiles:
    """Write vehicle, nested assembly, and formulation files for one case."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    baseline = configuration.__class__.open(configuration.source)
    changed = set(configuration.changed_from(baseline))
    changed.discard("model")

    # Copy each nesting component on a path to a changed slot.  Deepest first
    # means replacements are available when a parent is serialized.
    copies: set[str] = set()
    for key in changed:
        parts = key.split("/")
        for i in range(1, len(parts)):
            ancestor = "/".join(parts[:i])
            path = configuration.choices.get(ancestor)
            if path is not None and _components(path):
                copies.add(ancestor)
    copy_paths: dict[str, Path] = {key: directory / _output_name(key) for key in copies}

    for key in sorted(copies, key=lambda value: (value.count("/"), value), reverse=True):
        source = configuration.choices[key]
        replacements: dict[str, Path] = {}
        prefix = key + "/"
        for child_key, child_path in configuration.choices.items():
            if not child_key.startswith(prefix) or "/" in child_key[len(prefix):]:
                continue
            role = child_key[len(prefix):]
            replacements[role] = copy_paths.get(child_key, child_path)
        tree = _variant_tree(source, directory, case_id, replacements)
        _write_tree(tree, copy_paths[key], case_id, source)

    vehicle = directory / "vehicle.xml"
    vehicle_replacements: dict[str, Path] = {}
    for key, path in configuration.choices.items():
        if "/" not in key:
            vehicle_replacements[key] = copy_paths.get(key, path)
    vehicle_tree = _variant_tree(configuration.assembly, directory, case_id, vehicle_replacements)
    _write_tree(vehicle_tree, vehicle, case_id, configuration.assembly)

    formulation = directory / "formulation.xml"
    if configuration.formulation is None:
        vehicle_root = ElementTree.parse(configuration.assembly).getroot()
        root = ElementTree.Element("model", {
            "schema-version": "1.0",
            "id": f"{vehicle_root.get('id', '')}.{_case_suffix(case_id)}-formulation",
            "type": "vehicle-formulation",
            "subtype": configuration.model,
        })
        ElementTree.SubElement(root, "source", {"ref": "vehicle.xml"})
        formulation_tree = ElementTree.ElementTree(root)
        source = configuration.assembly
    else:
        source = configuration.formulation
        formulation_tree = ElementTree.parse(source)
        root = formulation_tree.getroot()
        original_subtype = root.get("subtype")
        root.set("id", f"{root.get('id', '')}.{_case_suffix(case_id)}")
        root.set("subtype", configuration.model)
        if original_subtype != configuration.model:
            for requires in root.findall("requires"):
                root.remove(requires)
        # The generated vehicle lives alongside this formulation.
        source_element = root.find("source")
        if source_element is None:
            raise ValueError(f"{source}: formulation has no source")
        source_element.set("ref", relative_reference(vehicle, directory))
        # Rewrite any data/reference paths in the formulation itself.
        rewrite_references(formulation_tree, source.parent, directory)
        source_element.set("ref", relative_reference(vehicle, directory))
    _write_tree(formulation_tree, formulation, case_id, source)
    return VariantFiles(formulation=formulation, vehicle=vehicle)
