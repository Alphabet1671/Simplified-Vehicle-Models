"""Write and check track files for the track GUI."""
from __future__ import annotations

import os
import re
import tempfile
from dataclasses import dataclass
from pathlib import Path

from simplified_vehicle_models.tracks.profile import load_track
from tools.gui_common.files import check_name, generated_by, protected_directory_problem
from tools.tracks.open_course import OpenCourse, write_course

MODEL_ID_PATTERN = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,79}")


class SaveRefused(Exception):
    """The save was refused by a safety rule. The message says which rule and what to do."""


@dataclass(frozen=True, slots=True)
class SavedTrack:
    xml: Path
    csv: Path
    length: float
    is_closed: bool
    node_count: int


def check_model_id(value: str) -> str:
    if not MODEL_ID_PATTERN.fullmatch(value or ""):
        raise ValueError(
            "the model id must be 1 to 80 characters of letters, digits, '.', '_' or '-', "
            "and must start with a letter or digit"
        )
    return value


def check_title(value: str) -> str:
    if not value.strip() or len(value) > 120 or "\n" in value:
        raise ValueError("the title must be one line of 1 to 120 characters")
    return value


def _guard_targets(
    directory: Path,
    stem: str,
    *,
    allow_models: bool,
    overwrite: bool,
    overwrite_generated: bool,
) -> None:
    problem = protected_directory_problem(directory, allow_models=allow_models)
    if problem:
        raise SaveRefused(problem)
    for suffix in (".xml", ".csv"):
        target = directory / f"{stem}{suffix}"
        if not target.exists():
            continue
        generator = generated_by(target) if suffix == ".xml" else None
        if generator and not overwrite_generated:
            raise SaveRefused(
                f"{target} is generated by {generator}. Change the file name, or confirm "
                "that you want to replace a generated file"
            )
        if not overwrite:
            raise SaveRefused(
                f"{target} already exists. Change the file name, or confirm the overwrite"
            )


def _install(temporary: Path, directory: Path, stem: str) -> tuple[Path, Path]:
    directory.mkdir(parents=True, exist_ok=True)
    csv_target, xml_target = directory / f"{stem}.csv", directory / f"{stem}.xml"
    # The CSV goes first: an XML that points at a missing CSV is the worse half-state.
    os.replace(temporary / f"{stem}.csv", csv_target)
    os.replace(temporary / f"{stem}.xml", xml_target)
    return xml_target, csv_target


def save_open_course(
    course: OpenCourse,
    directory: Path,
    stem: str,
    model_id: str,
    title: str,
    comments: list[str] = (),
    *,
    allow_models: bool = False,
    overwrite: bool = False,
    overwrite_generated: bool = False,
) -> SavedTrack:
    """Write an open course after every check, and read it back with ``load_track``.

    Nothing reaches ``directory`` unless the files load as a valid open track.
    """
    directory = Path(directory)
    check_name(stem, "file name")
    check_model_id(model_id)
    check_title(title)
    _guard_targets(
        directory,
        stem,
        allow_models=allow_models,
        overwrite=overwrite,
        overwrite_generated=overwrite_generated,
    )
    with tempfile.TemporaryDirectory() as folder:
        scratch = Path(folder)
        xml_path, _ = write_course(course, scratch, stem, model_id, title, list(comments))
        profile = load_track(xml_path)
        if profile.is_closed:
            raise ValueError("the written track loaded as a closed track")
        xml_target, csv_target = _install(scratch, directory, stem)
    return SavedTrack(xml_target, csv_target, float(profile.lap_length), False, int(profile.distance.size))


def describe_course(course: OpenCourse) -> dict[str, float]:
    """Return the numbers the status line shows."""
    import numpy as np

    curvature = np.asarray(course.curvature)
    peak = float(np.max(np.abs(curvature))) if curvature.size else 0.0
    return {
        "length_m": float(course.length),
        "nodes": int(len(course.distance)),
        "minimum_radius_m": (1.0 / peak) if peak > 1.0e-9 else float("inf"),
        "heading_change_deg": float(np.degrees(course.heading[-1] - course.heading[0])),
        "jumps": len(course.curvature_jumps),
    }
