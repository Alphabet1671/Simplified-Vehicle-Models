"""Build the Formula SAE acceleration and skidpad track models.

Both tracks are signed ``open-xy-profile`` models built with
``tools/tracks/open_course.py``. The point-mass lap solver reads their radius
and runs them in ``LapMode.STANDING_START``. The planar forward driver reads
their signed geometry. The geometry comes from the Formula SAE Rules 2026,
Version 1.0 (10 Sept 2025), Section D.9 and Section D.10.

Acceleration (D.9):

- The course is 75 m from the starting line to the finish line (D.9.1.1).
- The foremost part of the vehicle is staged 0.30 m behind the starting line,
  and timing starts when the vehicle crosses the line (D.9.2.3). The track
  therefore starts 0.30 m before the timed section.

Skidpad (D.10):

- Two pairs of concentric circles form a figure of eight. The centers are
  18.25 m apart. The inner circles are 15.25 m and the outer circles are
  21.25 m in diameter. The driving path is the 3.0 m wide ring between them
  (D.10.1.1).
- The run is one untimed right lap, one timed right lap, one untimed left lap,
  and one timed left lap, then the exit (D.10.2.3). The timed laps start and
  end on the start/stop line, which joins the two circle centers.
- The scored time is the mean of the timed right and left laps (D.10.4.1).

The path follows the centerline of the driving path, so the radius is
``(15.25 + 21.25) / 4 = 9.125`` m. Twice that radius is 18.25 m, which equals
the center spacing, so the two centerline circles touch on the start/stop line.
The entry straight, the right-to-left change and the exit straight all meet the
circles at that touching point and share one heading there.

At the touching point the curvature jumps from 0 to +1/R (entry), from +1/R to
-1/R (right to left), and from -1/R to 0 (exit). The rules define the geometry
and not a transition, so the course keeps the jumps. A table of nodes cannot
store a jump, so the builder replaces each by a 0.05 m ramp.

Not in the rule text: the rulebook gives the entry and exit lane geometry only
in a diagram. The entry and exit straights below are modelling choices and are
recorded as such in the track files. They only decide how fast the car arrives
at the first circle.

Run it only when the rules change. It needs only NumPy and the standard library::

    PYTHONPATH=src:. python3 tools/tracks/build_fsae_dynamic_tracks.py
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

from tools.tracks.open_course import (
    OpenCourse,
    arc_by_angle,
    build_course,
    csv_text,
    straight,
    transition,
    xml_text,
)


RULES_TITLE = "Formula SAE Rules 2026, Version 1.0, 10 Sept 2025"
RULES_URL = (
    "https://www.fsaeonline.com/cdsweb/gen/DownloadDocument.aspx"
    "?DocumentID=278fd4d7-aa27-4e33-bc4a-090148e662a0"
)
#: SHA-256 of the PDF fetched on 2026-10-19 from ``RULES_URL``.
RULES_SHA256 = "4620c33700f16bdc514a1e959b8746caef0a8878646c9b79b2ed01e8f790f7d8"

# Acceleration, D.9.
ACCELERATION_LENGTH = 75.0
ACCELERATION_STAGING_OFFSET = 0.30
ACCELERATION_MINIMUM_WIDTH = 4.9
ACCELERATION_NODE_SPACING = 0.30

# Skidpad, D.10.
SKIDPAD_CENTER_SPACING = 18.25
SKIDPAD_INNER_DIAMETER = 15.25
SKIDPAD_OUTER_DIAMETER = 21.25
SKIDPAD_PATH_WIDTH = 3.0
SKIDPAD_CIRCLE_RADIUS = (SKIDPAD_INNER_DIAMETER + SKIDPAD_OUTER_DIAMETER) / 4.0

# Modelling choices, not rule values.
SKIDPAD_ENTRY_LENGTH = 15.0
SKIDPAD_EXIT_LENGTH = 15.0
SKIDPAD_NODE_SPACING = 0.25
SKIDPAD_JUMP_RAMP_LENGTH = 0.05
SKIDPAD_TRANSITION_LENGTH = 0.0

_COMMENTS = [
    f"Source: {RULES_TITLE}, {RULES_URL} (PDF sha256 {RULES_SHA256}, fetched 2026-10-19). "
    "A later rules issue may differ.",
    "Generated by tools/tracks/build_fsae_dynamic_tracks.py. The point-mass solver reads the radius "
    "magnitude and the planar models read the signed curvature.",
]


def _check_skidpad_geometry() -> None:
    """Confirm the rule dimensions agree with each other."""

    width = (SKIDPAD_OUTER_DIAMETER - SKIDPAD_INNER_DIAMETER) / 2.0
    if not math.isclose(width, SKIDPAD_PATH_WIDTH):
        raise ValueError("skidpad path width does not match the circle diameters")
    if not math.isclose(2.0 * SKIDPAD_CIRCLE_RADIUS, SKIDPAD_CENTER_SPACING):
        raise ValueError("skidpad centerline circles must touch on the start/stop line")


def acceleration_course() -> tuple[OpenCourse, dict[str, float]]:
    """Return the acceleration course and its timing window."""

    total = ACCELERATION_STAGING_OFFSET + ACCELERATION_LENGTH
    count = total / ACCELERATION_NODE_SPACING
    if not math.isclose(count, round(count), abs_tol=1.0e-9):
        raise ValueError("the node spacing must divide the staged course length")
    course = build_course(
        [straight(total, "acceleration course")], maximum_spacing=ACCELERATION_NODE_SPACING
    )
    window = {
        "timing_start_distance": ACCELERATION_STAGING_OFFSET,
        "timing_end_distance": total,
    }
    return course, window


def skidpad_course(
    transition_length: float = SKIDPAD_TRANSITION_LENGTH,
) -> tuple[OpenCourse, dict[str, float]]:
    """Return the skidpad course and the distances of its timed laps.

    The path is the entry straight, two right laps, two left laps, and the exit
    straight. Right is positive curvature.

    ``transition_length`` is the length in metres of the clothoid that changes
    curvature from +1/R to -1/R. The entry and exit change +-1/R, half as much,
    at the same curvature rate. Zero keeps the rule geometry, with each curvature
    jump replaced by a ``SKIDPAD_JUMP_RAMP_LENGTH`` ramp.
    """

    _check_skidpad_geometry()
    lap = 2.0 * math.pi
    radius = SKIDPAD_CIRCLE_RADIUS
    curvature = 1.0 / radius
    if transition_length > 0.0:
        rate = 2.0 * curvature / transition_length
        link = lambda start, end, name: transition(start, end, rate, name)  # noqa: E731
        entry = [link(0.0, curvature, "entry transition")]
        change = [link(curvature, -curvature, "right-to-left transition")]
        leave = [link(-curvature, 0.0, "exit transition")]
    else:
        entry = change = leave = []
    course = build_course(
        [
            straight(SKIDPAD_ENTRY_LENGTH, "entry"),
            *entry,
            arc_by_angle(radius, lap, "right lap 1 (untimed)"),
            arc_by_angle(radius, lap, "right lap 2 (timed)"),
            *change,
            arc_by_angle(radius, -lap, "left lap 1 (untimed)"),
            arc_by_angle(radius, -lap, "left lap 2 (timed)"),
            *leave,
            straight(SKIDPAD_EXIT_LENGTH, "exit"),
        ],
        maximum_spacing=SKIDPAD_NODE_SPACING,
        allow_curvature_jumps=True,
        jump_ramp_length=SKIDPAD_JUMP_RAMP_LENGTH,
    )
    starts = dict(zip(course.names, course.boundaries[:-1]))
    ends = dict(zip(course.names, course.boundaries[1:]))
    window = {
        "right_timed_lap_start_distance": starts["right lap 2 (timed)"],
        "right_timed_lap_end_distance": ends["right lap 2 (timed)"],
        "left_timed_lap_start_distance": starts["left lap 2 (timed)"],
        "left_timed_lap_end_distance": ends["left lap 2 (timed)"],
    }
    return course, window


def acceleration_files() -> dict[str, str]:
    """Return the file contents of the acceleration track."""

    course, window = acceleration_course()
    comments = _COMMENTS + [
        "D.9.1.1 course length 75 m from starting line to finish line. D.9.2.3 the foremost part of the "
        "vehicle is staged 0.30 m behind the starting line and timing starts at the line, so the run starts "
        "at distance 0 and the timed section is timing_start_distance to timing_end_distance. The minimum "
        "course width of 4.9 m (D.9.1.2) does not enter a centerline path.",
        "The course heads north from the origin.",
    ]
    parameters = [
        ("node_spacing", ACCELERATION_NODE_SPACING, "m"),
        ("rule_course_length", ACCELERATION_LENGTH, "m"),
        ("staging_offset", ACCELERATION_STAGING_OFFSET, "m"),
        ("minimum_course_width", ACCELERATION_MINIMUM_WIDTH, "m"),
        ("timing_start_distance", window["timing_start_distance"], "m"),
        ("timing_end_distance", window["timing_end_distance"], "m"),
    ]
    stem = "fsae_2026_acceleration"
    return {
        f"{stem}.csv": csv_text(course),
        f"{stem}.xml": xml_text(
            course, "fsae-2026-acceleration", "FSAE 2026 Acceleration", f"{stem}.csv",
            comments, parameters, (RULES_SHA256, f"{RULES_TITLE}, D.9"),
        ),
    }


def skidpad_files() -> dict[str, str]:
    """Return the file contents of the skidpad track."""

    course, window = skidpad_course()
    comments = _COMMENTS + [
        "D.10.1.1 centers 18.25 m apart, inner circles 15.25 m and outer circles 21.25 m in diameter, 3.0 m "
        "driving path. The path is the ring centerline, radius (15.25 + 21.25) / 4 = 9.125 m. "
        "D.10.2.3 the run is right lap (untimed), right lap (timed), left lap (untimed), left lap (timed), "
        "then exit. D.10.4.1 the scored time is the mean of the two timed laps.",
        "The entry and exit straights are modelling choices, not rule values, because the rules give the "
        "lane geometry only in a diagram. The course heads north from the origin and the circles touch at "
        "the end of the entry straight. Each curvature jump there is a 0.05 m ramp in the table.",
    ]
    parameters = [
        ("node_spacing", SKIDPAD_NODE_SPACING, "m"),
        ("jump_ramp_length", SKIDPAD_JUMP_RAMP_LENGTH, "m"),
        ("circle_radius", SKIDPAD_CIRCLE_RADIUS, "m"),
        ("circle_center_spacing", SKIDPAD_CENTER_SPACING, "m"),
        ("inner_circle_diameter", SKIDPAD_INNER_DIAMETER, "m"),
        ("outer_circle_diameter", SKIDPAD_OUTER_DIAMETER, "m"),
        ("driving_path_width", SKIDPAD_PATH_WIDTH, "m"),
        ("entry_length_assumed", SKIDPAD_ENTRY_LENGTH, "m"),
        ("exit_length_assumed", SKIDPAD_EXIT_LENGTH, "m"),
    ] + [(key, value, "m") for key, value in window.items()]
    stem = "fsae_2026_skidpad"
    return {
        f"{stem}.csv": csv_text(course),
        f"{stem}.xml": xml_text(
            course, "fsae-2026-skidpad", "FSAE 2026 Skidpad", f"{stem}.csv",
            comments, parameters, (RULES_SHA256, f"{RULES_TITLE}, D.10"),
        ),
    }


def all_files() -> dict[str, str]:
    """Return every generated file by name."""

    return {**acceleration_files(), **skidpad_files()}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output-dir", type=Path, default=Path("models/tracks"))
    options = parser.parse_args()
    options.output_dir.mkdir(parents=True, exist_ok=True)
    for name, text in all_files().items():
        (options.output_dir / name).write_text(text, encoding="utf-8")
        print(f"wrote {options.output_dir / name}")


if __name__ == "__main__":
    main()
