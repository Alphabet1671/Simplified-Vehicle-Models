"""An editable vehicle: parameter edits and component swaps on top of a configuration.

Nothing here writes a file. ``tools.vehicle_gui.save`` turns a ``VehicleEdit`` into files.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field, replace
from pathlib import Path

from tools.gui_common.files import generated_by
from tools.sim_gui.vehicle import VehicleConfiguration
from tools.vehicle_gui import xmltext

ASSEMBLY = ""  # the slot key of the vehicle assembly file itself


@dataclass(frozen=True, slots=True)
class ParameterRow:
    name: str
    original: str
    unit: str
    edited: float | None

    @property
    def value_text(self) -> str:
        return self.original if self.edited is None else xmltext.format_number(self.edited)

    @property
    def numeric(self) -> bool:
        try:
            float(self.original)
        except ValueError:
            return False
        return True


@dataclass(frozen=True, slots=True)
class VehicleEdit:
    configuration: VehicleConfiguration
    baseline: VehicleConfiguration
    parameters: dict[str, dict[str, float]] = field(default_factory=dict)

    @classmethod
    def open(cls, path: Path) -> "VehicleEdit":
        configuration = VehicleConfiguration.open(Path(path))
        if configuration.formulation is None:
            raise ValueError("vehicle GUI requires a vehicle-formulation; a bare vehicle-assembly has no subtype")
        if configuration.model not in {"planar-7dof", "14dof-simple"}:
            raise ValueError(f"unsupported vehicle formulation subtype: {configuration.model}")
        return cls(configuration, configuration, {})

    def keys(self) -> tuple[str, ...]:
        """The slot keys, with the assembly first."""
        return (ASSEMBLY, *(slot.key for slot in self.configuration.slots()))

    def file(self, key: str) -> Path:
        if key == ASSEMBLY:
            return self.configuration.assembly
        try:
            return self.configuration.choices[key]
        except KeyError:
            raise ValueError(f"unknown slot {key!r}") from None

    def generator(self, key: str) -> str | None:
        """The tool that generated this slot's file, or None when it is hand-written."""
        return generated_by(self.file(key))

    def rows(self, key: str) -> list[ParameterRow]:
        text = self.file(key).read_text(encoding="utf-8")
        units = xmltext.parameter_units(text)
        edits = self.parameters.get(key, {})
        return [
            ParameterRow(name, value, units.get(name, ""), edits.get(name))
            for name, value in xmltext.parameter_values(text).items()
        ]

    def swapped(self) -> tuple[str, ...]:
        return tuple(key for key in self.configuration.changed_from(self.baseline) if key != "model")

    def edited_keys(self) -> tuple[str, ...]:
        return tuple(key for key, values in self.parameters.items() if values)

    @property
    def changed(self) -> bool:
        return bool(self.swapped() or self.edited_keys())

    def with_parameter(self, key: str, name: str, value: float) -> "VehicleEdit":
        if not math.isfinite(value):
            raise ValueError(f"{name}: the value must be finite")
        row = next((row for row in self.rows(key) if row.name == name), None)
        if row is None:
            raise ValueError(f"{key or 'assembly'} has no parameter {name!r}")
        if not row.numeric:
            raise ValueError(f"{name} is not a number and cannot be edited here")
        if self.generator(key):
            raise ValueError(
                f"{self.file(key).name} is generated by {self.generator(key)}. "
                f"Change the inputs of that tool instead of the file"
            )
        parameters = {k: dict(v) for k, v in self.parameters.items()}
        if value == float(row.original):
            parameters.get(key, {}).pop(name, None)
        else:
            parameters.setdefault(key, {})[name] = float(value)
        parameters = {k: v for k, v in parameters.items() if v}
        return replace(self, parameters=parameters)

    def without_parameter(self, key: str, name: str) -> "VehicleEdit":
        parameters = {k: dict(v) for k, v in self.parameters.items()}
        parameters.get(key, {}).pop(name, None)
        return replace(self, parameters={k: v for k, v in parameters.items() if v})

    def with_choice(self, key: str, path: Path) -> "VehicleEdit":
        configuration = self.configuration.with_choice(key, path)
        prefix = key + "/"
        parameters = {k: v for k, v in self.parameters.items() if k != key and not k.startswith(prefix)}
        return replace(self, configuration=configuration, parameters=parameters)

    def reset(self) -> "VehicleEdit":
        return replace(self, configuration=self.baseline, parameters={})
