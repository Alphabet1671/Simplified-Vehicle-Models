"""Turn a ``VehicleEdit`` into files, and check them with the real compiler.

The originals are never written: saves render copies in a temporary sibling,
validate those copies, then commit the complete validated set transactionally.
"""
from __future__ import annotations

import os
import re
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path

from simplified_vehicle_models.compiler.compile import compile_formulation
from tools.gui_common import REPOSITORY_ROOT
from tools.gui_common.files import atomic_write_text, check_name, protected_directory_problem
from tools.vehicle_gui import xmltext
from tools.vehicle_gui.model import ASSEMBLY, VehicleEdit

_DECLARATION = re.compile(r"\A(<\?xml[^>]*\?>[ \t]*\r?\n)")
_GENERATED = re.compile(r"Generated by (tools/[\w./-]+)")


class SaveRefused(Exception):
    """A safety rule stopped the save."""


@dataclass(frozen=True, slots=True)
class Validation:
    error: str | None
    unconsumed: tuple[str, ...] = ()
    unused_roles: tuple[str, ...] = ()

    @property
    def ok(self) -> bool:
        return self.error is None


@dataclass(frozen=True, slots=True)
class SavedVehicle:
    entry: Path
    files: tuple[Path, ...]
    validation: Validation


def _relative(target: Path, directory: Path) -> str:
    return Path(os.path.relpath(Path(target).resolve(), Path(directory).resolve())).as_posix()


def _declared_child(parent_file: Path, role: str) -> Path | None:
    from xml.etree import ElementTree

    for component in ElementTree.parse(parent_file).getroot().findall("./components/component"):
        if component.get("role") == role and component.get("ref"):
            return (Path(parent_file).parent / component.get("ref")).resolve()
    return None


def diverging_keys(edit: VehicleEdit) -> set[str]:
    result: set[str] = set()
    for key, path in edit.configuration.choices.items():
        parent, _, role = key.rpartition("/")
        declared = _declared_child(edit.file(parent), role)
        if declared is None or declared != Path(path).resolve():
            result.add(key)
    return result


def _copied_keys(edit: VehicleEdit) -> set[str]:
    changed = set(edit.edited_keys()) | diverging_keys(edit)
    copied = {ASSEMBLY} | set(edit.edited_keys())
    for key in changed:
        parts = key.split("/")
        copied.update("/".join(parts[:count]) for count in range(1, len(parts)))
    return copied


def _mark_copy(text: str, source: Path) -> str:
    def neutral(match: re.Match[str]) -> str:
        return "<!--" + _GENERATED.sub(
            r"Derived from output of \1", match.group(0)[4:-3]
        ).replace("Do not edit.", "This copy was saved by tools/vehicle_gui.") + "-->"

    text = re.sub(r"<!--.*?-->", neutral, text, flags=re.S)
    try:
        origin = Path(source).resolve().relative_to(REPOSITORY_ROOT).as_posix()
    except ValueError:
        origin = Path(source).name
    note = f"<!-- Saved by tools/vehicle_gui from {origin}. -->\n"
    match = _DECLARATION.match(text)
    return text[:match.end()] + note + text[match.end():] if match else note + text


def _name(stem: str, key: str) -> str:
    return f"{stem}__vehicle.xml" if key == ASSEMBLY else f"{stem}__{key.replace('/', '__')}.xml"


def render_files(edit: VehicleEdit, directory: Path, stem: str) -> list[tuple[Path, str]]:
    """Return ``(path, text)`` for every file, children first and formulation last."""
    directory = Path(directory).resolve()
    check_name(stem, "file name")
    for key in edit.edited_keys():
        if edit.generator(key):
            raise ValueError(f"{edit.file(key).name} is generated by {edit.generator(key)} and cannot be edited")
    copied = _copied_keys(edit)
    swapped = diverging_keys(edit)
    paths = {key: directory / _name(stem, key) for key in copied}
    configuration = edit.configuration
    if configuration.formulation is None:
        raise ValueError("vehicle GUI requires a vehicle-formulation")
    output: list[tuple[Path, str]] = []
    for key in sorted(copied, key=lambda k: (-(k.count("/") + (k != ASSEMBLY)), k)):
        source = edit.file(key)
        text = source.read_text(encoding="utf-8")
        text = xmltext.reanchor(text, source.parent, directory)
        text = xmltext.set_model_id(text, f"{xmltext.model_id(text)}.{stem}")
        if edit.parameters.get(key):
            text = xmltext.set_parameters(text, edit.parameters[key])
        prefix = f"{key}/" if key else ""
        for child in configuration.choices:
            if not child.startswith(prefix) or "/" in child[len(prefix):] or child == key:
                continue
            if child in copied or child in swapped:
                target = paths.get(child, configuration.choices[child])
                text = xmltext.set_component_ref(text, child[len(prefix):], _relative(target, directory))
        output.append((paths[key], _mark_copy(text, source)))
    source = configuration.formulation
    text = xmltext.reanchor(source.read_text(encoding="utf-8"), source.parent, directory)
    text = xmltext.set_model_id(text, f"{xmltext.model_id(text)}.{stem}")
    text = xmltext.set_source_ref(text, _relative(paths[ASSEMBLY], directory))
    output.append((directory / f"{stem}__formulation.xml", _mark_copy(text, source)))
    return output


def _validation(compiled) -> Validation:
    manifest = compiled.manifest
    return Validation(
        None,
        tuple(f"{item.name} = {item.value:g} {item.unit}".strip() for item in manifest.unconsumed_parameters),
        tuple(manifest.unused_roles()),
    )


def check_files(edit: VehicleEdit, stem: str = "check") -> Validation:
    try:
        with tempfile.TemporaryDirectory() as folder:
            scratch = Path(folder)
            files = render_files(edit, scratch, stem)
            for path, text in files:
                atomic_write_text(path, text)
            compiled = compile_formulation(files[-1][0])
            return _validation(compiled)
    except (ValueError, OSError) as error:
        return Validation(str(error).replace(str(Path(tempfile.gettempdir()).resolve()), "<scratch>"))


def save_vehicle(edit: VehicleEdit, directory: Path, stem: str, *, allow_models: bool = False,
                 overwrite: bool = False) -> SavedVehicle:
    """Render, validate, and commit a vehicle as one best-effort transaction."""
    directory = Path(directory).expanduser().resolve()
    problem = protected_directory_problem(directory, allow_models=allow_models)
    if problem:
        raise SaveRefused(problem)
    check_name(stem, "file name")
    directory.parent.mkdir(parents=True, exist_ok=True)
    stage = Path(tempfile.mkdtemp(prefix=f".{stem}.", dir=directory.parent))
    retain_stage = False
    try:
        staged = render_files(edit, stage, stem)
        for path, text in staged:
            atomic_write_text(path, text)
        compiled = compile_formulation(staged[-1][0])
        validation = _validation(compiled)
        final = [directory / path.relative_to(stage) for path, _ in staged]
        stale = set(directory.glob(f"{stem}__*.xml")) - set(final)
        existing = [path for path in [*final, *sorted(stale)] if path.exists()]
        if existing and not overwrite:
            raise SaveRefused(f"{existing[0]} already exists. Change the file name, or confirm the overwrite")
        backup = stage / ".backup"
        backup.mkdir()
        moved: list[Path] = []
        backed_up: list[tuple[Path, Path]] = []
        try:
            for target in existing:
                saved = backup / target.name
                os.replace(target, saved)
                backed_up.append((target, saved))
            for source, target in zip((path for path, _ in staged), final):
                target.parent.mkdir(parents=True, exist_ok=True)
                os.replace(source, target)
                moved.append(target)
        except Exception as original_error:
            rollback_errors: list[Exception] = []
            for target in moved:
                try:
                    target.unlink(missing_ok=True)
                except Exception as error:
                    rollback_errors.append(error)
            for target, saved in reversed(backed_up):
                try:
                    os.replace(saved, target)
                except Exception as error:
                    rollback_errors.append(error)
            if rollback_errors:
                retain_stage = True
                original_error.add_note(f"rollback incomplete; recover backups from {stage}")
            raise original_error
        return SavedVehicle(final[-1], tuple(final), validation)
    except SaveRefused:
        raise
    except (ValueError, OSError) as error:
        if isinstance(error, ValueError):
            raise
        converted = ValueError(str(error))
        for note in getattr(error, "__notes__", ()):
            converted.add_note(note)
        raise converted from error
    finally:
        if not retain_stage:
            shutil.rmtree(stage, ignore_errors=True)


def save_component(source: Path, values: dict[str, float], directory: Path, stem: str, model_id: str, *,
                   allow_models: bool = False, overwrite: bool = False) -> Path:
    """Save one component copy after a temporary loader check."""
    source, directory = Path(source).resolve(), Path(directory).expanduser().resolve()
    check_name(stem, "file name")
    problem = protected_directory_problem(directory, allow_models=allow_models)
    if problem:
        raise SaveRefused(problem)
    target = directory / f"{stem}.xml"
    if target.exists() and not overwrite:
        raise SaveRefused(f"{target} already exists. Change the file name, or confirm the overwrite")
    text = source.read_text(encoding="utf-8")
    if _GENERATED.search(text) and values:
        raise ValueError(f"{source.name} is generated; change the inputs of its tool instead")
    text = xmltext.reanchor(text, source.parent, directory)
    text = xmltext.set_model_id(text, model_id)
    if values:
        text = xmltext.set_parameters(text, values)
    text = _mark_copy(text, source)
    from simplified_vehicle_models.xml.loader import load_model
    with tempfile.TemporaryDirectory() as folder:
        probe = Path(folder) / "probe.xml"
        atomic_write_text(probe, xmltext.reanchor(text, directory, Path(folder)))
        load_model(probe)
    atomic_write_text(target, text)
    return target
